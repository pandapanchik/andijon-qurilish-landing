const listeners = new Set();
let current = 'uz';

export const t = (key) => dict[current][key] ?? dict.uz[key] ?? key;
export const lang = () => current;
export const onLangChange = (fn) => listeners.add(fn);

export function setLang(next) {
  current = dict[next] ? next : 'uz';
  document.documentElement.lang = current;
  document.title = t('meta.title');
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
  document.querySelectorAll('[data-lang]').forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.lang === current)));
  try { localStorage.setItem('aqh-lang', current); } catch { /* storage may be blocked */ }
  listeners.forEach((fn) => fn(current));
}

export function initLang() {
  let saved = null;
  try { saved = localStorage.getItem('aqh-lang'); } catch { /* ignore */ }
  document.querySelectorAll('[data-lang]').forEach((b) => b.addEventListener('click', () => setLang(b.dataset.lang)));
  setLang(saved || 'uz');
}
